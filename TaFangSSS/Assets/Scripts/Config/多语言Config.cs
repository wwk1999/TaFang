        /// <summary>取翻译；未收录时返回简体原文。</summary>
        public static string Get(string 简体中文)
        {
            if (string.IsNullOrEmpty(简体中文)) return 简体中文;
            if (当前语言 == 语言Type.简体中文) return 简体中文;

            if (词条.TryGetValue(简体中文, out var 译文))
            {
                return 译文[(int)当前语言 - 1];
            }

            // 预制体里的多行文本会带换行，词条表里用 " / " 表示换行
            string 单行 = 简体中文.Replace("\r", "").Replace("\n", " / ");
            if (单行 != 简体中文 && 词条.TryGetValue(单行, out var 换行译文))
            {
                return 换行译文[(int)当前语言 - 1];
            }

            // 「地无暇提示」这类前后缀组合文本
            const string 无暇后缀 = "无暇提示";
            if (简体中文.EndsWith(无暇后缀) && 简体中文.Length > 无暇后缀.Length)
            {
                string 前缀 = 简体中文.Substring(0, 简体中文.Length - 无暇后缀.Length);
                return Get("{0}无暇提示", Get(前缀 + "品"));
            }

            // 「玄品解锁」这类品质+动作的文本
            const string 解锁后缀 = "解锁";
            if (简体中文.EndsWith(解锁后缀) && 简体中文.Length > 解锁后缀.Length)
            {
                string 前缀 = 简体中文.Substring(0, 简体中文.Length - 解锁后缀.Length);
                return Get("{0}解锁", Get(前缀));
            }

            // 「攻击力+99999」「射手伤害增幅+36%」这类属性展示
            int 加号位置 = 简体中文.IndexOf('+');
            if (加号位置 > 0 && 加号位置 < 简体中文.Length - 1)
            {
                string 名称 = 简体中文.Substring(0, 加号位置);
                string 数值 = 简体中文.Substring(加号位置 + 1);
                if (词条.ContainsKey(名称))
                {
                    return 数值.EndsWith("%")
                        ? Get("{0}+{1}%", Get(名称), 数值.TrimEnd('%'))
                        : Get("{0}+{1}", Get(名称), 数值);
                }
            }

            // 兜底：「12阶」这类纯数字+阶的文本不必逐条录入
            if (简体中文.Length > 1 && 简体中文[简体中文.Length - 1] == '阶')
            {
                string 数字 = 简体中文.Substring(0, 简体中文.Length - 1);
                if (int.TryParse(数字, out int n)) return 阶数文本(n);
            }
            return 简体中文;
        }

        /// <summary>带占位符的翻译，模板里用 {0} {1}。</summary>
        public static string Get(string 简体中文模板, params object[] 参数)
        {
            string 模板 = Get(简体中文模板);
            if (参数 == null || 参数.Length == 0) return 模板;
            try
            {
                return string.Format(模板, 参数);
            }
            catch (FormatException)
            {
                return 模板;
            }
        }

        /// <summary>
        /// 把任意语言的译文还原成简体中文 key。
        /// 用于「组件挂晚了一步、文本已经是译文」的情况，避免重复翻译或语言切不回去。
        /// 查不到返回 null。
        /// </summary>
        public static string 还原原文(string 文本)
        {
            if (string.IsNullOrEmpty(文本)) return null;
            if (词条.ContainsKey(文本)) return 文本;

            for (int 语言 = 1; 语言 < 反查表.Length; 语言++)
            {
                var 表 = 反查表[语言];
                if (表 == null)
                {
                    表 = new Dictionary<string, string>(词条.Count);
                    foreach (var kv in 词条)
                    {
                        string 译文 = kv.Value[语言 - 1];
                        if (!string.IsNullOrEmpty(译文)) 表[译文] = kv.Key;
                    }
                    反查表[语言] = 表;
                }
                if (表.TryGetValue(文本, out string 简中)) return 简中;
            }
            return null;
        }

        public static string 阶数文本(int n)
        {
            switch (当前语言)
            {
                case 语言Type.繁体中文: return n + "階";
                case 语言Type.英文: return "Tier " + n;
                case 语言Type.日文: return n + "階";
                case 语言Type.韩文: return n + "단계";
                case 语言Type.泰文: return "ขั้น " + n;
                default: return n + "阶";
            }
        }

