    private static readonly (double value, string symbol)[] Units = new (double, string)[]
    {
        (1e28, "穰"),  // 10^28
        (1e24, "秭"),  // 10^24
        (1e20, "垓"),  // 10^20
        (1e16, "京"),  // 10^16
        (1e12, "兆"),  // 10^12
        (1e8,  "亿"),  // 10^8
        (1e4,  "万")   // 10^4
    };
    
    public string 格式化数字(double num)
    {
        // 处理负数
        if (num < 0)
        {
            return "-" + 格式化数字(Math.Abs(num));
        }

        // 小于1万直接显示整数
        if (num < 1000000)
        {
            return Math.Floor(num).ToString();
        }

        // 从大到小遍历单位
        foreach (var unit in Units)
        {
            // 达到当前单位的1000倍才转换（即 1000万、1000亿、1000兆...）
            if (num >= unit.value * 100)
            {
                int v = (int)(num / unit.value);
                return v + unit.symbol;
            }
        }

        // 超大数值降级为科学计数法
        return num.ToString("E1");
    }

